//! The registry's union `TypeCode` against the one a conformant peer derives
//! from the same IDL — member for member.
//!
//! Every byte sequence below was captured from omniORB 4.3.4 (omniORBpy,
//! `cdrMarshal(CORBA._tc_TypeCode, tc, endian)`, the TypeCode built by
//! `omniidl -bpython` from the corpus IDL) on 2026-08-19 by
//! `spikes/union_default_capture.py`, which retakes them from the live fixture
//! and compares outside the padding — clause (b) of the licensing boundary,
//! the output of a program we ran, describing IDL we wrote. Each union is
//! recorded in a little-endian and a big-endian stream; omniORB writes the
//! encapsulation little-endian in both (only the kind and the length flip),
//! so the big-endian recording is the one where the stream's order and the
//! body's differ, which is what a decoder gets wrong.
//!
//! What is compared here is the **shape**, not the bytes: the peer's bytes
//! decoded by `orbweaver_giop::typecode::decode` (which drops the default
//! member's ignored label, §9.3.5.1.4) against the `TypeCode` the registry
//! derives from `corpus/golden/06-union.idl` and `29-labelled-default.idl`,
//! by `==` — id, name, discriminator, `default_index`, and every member's
//! label, name and type, in order. That is the CORBA `TypeCode::equal`
//! relation over the fields the wire carries; nothing weaker (`equivalent`
//! unaliases and ignores names, and would pass a member list in the wrong
//! order for the same reason).
//!
//! Until 2026-08-19 it was false for three of the four. omniidl lists one
//! member per label **with the `default:` a member of its own, where it was
//! written**: `case 2: default: string rest;` is `(1, one)`, `(2, rest)`,
//! default `rest`, `default_index` 2; `default: case 5: case 6: short misc;
//! case 7: long seven;` is the default `misc` first, `default_index` 0. The
//! registry folded a labelled default onto its label — `Coded` had two
//! members with `default_index` 1, `Spread` three with `default_index` 0 on
//! `(5, misc)`. Both peers selected the same branch from either form for
//! every discriminator (measured, 3a061d8), so it was not an
//! interoperability failure at the value level; it was a different
//! `member_count` and `default_index` on the wire, a `TypeCode` no peer's
//! IDL-derived one equalled, and a `case 2:` lost by anything that
//! regenerated IDL from our own decoded TypeCode. `WithDefault` — a bare
//! default — was equal before and after, and is here so a change that made
//! the labelled shape equal by breaking the bare one would still be red.


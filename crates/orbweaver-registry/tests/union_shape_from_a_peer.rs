/// (what, golden file, repository id, bytes, the stream's byte order)
type Recording = (&'static str, &'static str, &'static str, &'static [u8], Endian);

fn recordings() -> Vec<Recording> {
    let (le, be) = (Endian::Little, Endian::Big);
    let g06 = "06-union.idl";
    let g29 = "29-labelled-default.idl";
    vec![
        ("WithDefault LE", g06, "IDL:gc06/WithDefault:1.0", GOLDEN_06_WITH_DEFAULT_LITTLE, le),
        ("WithDefault BE", g06, "IDL:gc06/WithDefault:1.0", GOLDEN_06_WITH_DEFAULT_BIG, be),
        ("Coded LE", g29, "IDL:gc29/Coded:1.0", GOLDEN_29_CODED_LITTLE, le),
        ("Coded BE", g29, "IDL:gc29/Coded:1.0", GOLDEN_29_CODED_BIG, be),
        ("Spread LE", g29, "IDL:gc29/Spread:1.0", GOLDEN_29_SPREAD_LITTLE, le),
        ("Spread BE", g29, "IDL:gc29/Spread:1.0", GOLDEN_29_SPREAD_BIG, be),
        ("Tint LE", g29, "IDL:gc29/Tint:1.0", GOLDEN_29_TINT_LITTLE, le),
        ("Tint BE", g29, "IDL:gc29/Tint:1.0", GOLDEN_29_TINT_BIG, be),
    ]
}

fn golden(name: &str) -> Registry {
    let path: PathBuf =
        Path::new(env!("CARGO_MANIFEST_DIR")).join("../..").join("corpus/golden").join(name);
    let src = std::fs::read_to_string(&path)
        .unwrap_or_else(|e| panic!("cannot read {}: {e}", path.display()));
    let spec =
        orbweaver_idl::parse(&src).unwrap_or_else(|e| panic!("{} must parse: {e}", path.display()));
    let mut reg = Registry::new();
    reg.load(&spec).unwrap_or_else(|e| panic!("{} must load: {e}", path.display()));
    reg
}

/// A union's member list as `(label, name)` pairs plus its default index —
/// the part of the comparison worth reading when it fails.
fn members(tc: &TypeCode) -> (Vec<(Vec<u8>, String)>, i32) {
    let TypeCode::Union { cases, default_index, .. } = tc else { panic!("not a union: {tc:?}") };
    (cases.iter().map(|c| (c.label.clone(), c.name.clone())).collect(), *default_index)
}

/// Every recording, both stream orders, one pass: what omniORB wrote for the
/// union, decoded, **equals** what the registry derives from the same IDL.
/// The whole `TypeCode`, not a projection — a projection is where a fold
/// hides.
#[test]
fn the_registry_derives_the_member_list_omniidl_derives() {
    let mut failures = Vec::new();
    for (what, file, id, bytes, endian) in recordings() {
        let peer = match decode(&mut Decoder::new(bytes, endian)) {
            Ok(tc) => tc,
            Err(e) => {
                failures.push(format!("{what}: the peer's bytes do not decode: {e}"));
                continue;
            }
        };
        let ours = golden(file).typecode(id).unwrap_or_else(|| panic!("{file}: {id}")).clone();
        if ours != peer {
            failures.push(format!(
                "{what}: not equal\n    ours (members, default) {:?}\n    peer                    {:?}\n    ours {ours:?}\n    peer {peer:?}",
                members(&ours),
                members(&peer)
            ));
        }
    }
    assert!(failures.is_empty(), "{} failure(s):\n  {}", failures.len(), failures.join("\n  "));
}

/// The composition a peer actually meets: our TypeCode encoded by us, in
/// either byte order, read back, equals the peer's IDL-derived one. The test
/// above holds the registry to the peer and `union_default_round_trip` holds
/// the codec to itself; this holds the two together, so a codec that
/// canonicalised the member list on the way out could not pass both halves
/// separately and fail the whole.
#[test]
fn ours_re_encoded_reads_back_equal_to_the_peers_in_either_byte_order() {
    let mut failures = Vec::new();
    for (what, file, id, bytes, endian) in recordings() {
        let peer = decode(&mut Decoder::new(bytes, endian)).expect("the peer's bytes decode");
        let ours = golden(file).typecode(id).unwrap_or_else(|| panic!("{file}: {id}")).clone();
        for out in [Endian::Big, Endian::Little] {
            let mut e = Encoder::new(out);
            encode(&mut e, &ours).expect("encode");
            let wire = e.finish().expect("finish");
            match decode(&mut Decoder::new(&wire, out)) {
                Err(e) => failures.push(format!("{what} via {out:?}: ours does not decode: {e}")),
                Ok(back) if back != peer => failures.push(format!(
                    "{what} via {out:?}: {:?} != the peer's {:?}",
                    members(&back),
                    members(&peer)
                )),
                Ok(_) => {}
            }
        }
    }
    assert!(failures.is_empty(), "{} failure(s):\n  {}", failures.len(), failures.join("\n  "));
}

/// The expansion, spelled out: one member per label, the `default:` a member
/// of its own with no label, in source order, `default_index` on it. Pinned
/// in words as well as bytes, so the shape is readable here and not only in
/// a hex dump; and pinned against the *registry*, which is what changed —
/// `orbweaver_giop`'s `union_default_label_from_a_peer` pins the peer's side
/// of the same fact.
#[test]
fn a_labelled_default_is_one_member_per_label_default_included() {
    let g29 = golden("29-labelled-default.idl");
    let l = |v: i32| v.to_be_bytes().to_vec();
    let s = |v: i16| v.to_be_bytes().to_vec();
    let m = |pairs: &[(Vec<u8>, &str)]| -> Vec<(Vec<u8>, String)> {
        pairs.iter().map(|(a, b)| (a.clone(), (*b).to_owned())).collect()
    };
    let cases = [
        (
            "IDL:gc29/Coded:1.0",
            m(&[(l(1), "one"), (l(2), "rest"), (Vec::new(), "rest")]),
            2,
            "case 2: default: string rest; — the label first, then the default",
        ),
        (
            "IDL:gc29/Spread:1.0",
            m(&[(Vec::new(), "misc"), (s(5), "misc"), (s(6), "misc"), (s(7), "seven")]),
            0,
            "default: case 5: case 6: short misc; — the default first",
        ),
        (
            "IDL:gc29/Tint:1.0",
            m(&[(l(0), "warm"), (l(1), "named"), (Vec::new(), "named")]),
            2,
            "case GREEN: default: string named; — over an enum, GREEN then the default",
        ),
    ];
    let mut failures = Vec::new();
    for (id, want, default_index, why) in cases {
        let tc = g29.typecode(id).unwrap_or_else(|| panic!("{id}"));
        let got = members(tc);
        if got != (want.clone(), default_index) {
            failures.push(format!(
                "{id}: {why}\n    want {want:?} default {default_index}\n    got  {got:?}"
            ));
        }
    }
    assert!(failures.is_empty(), "{} failure(s):\n  {}", failures.len(), failures.join("\n  "));
}

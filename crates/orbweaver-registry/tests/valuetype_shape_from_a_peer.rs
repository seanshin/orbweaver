//! The registry's `valuetype` and `abstract interface` `TypeCode`s against the
//! ones a conformant peer derives from the same IDL — field for field.
//!
//! Every byte sequence below was captured from omniORB 4.3.4 (omniORBpy,
//! `cdrMarshal(CORBA._tc_TypeCode, tc, endian)`, the TypeCode built by
//! `omniidl -bpython` from the corpus files this test loads) on 2026-08-20 by
//! `spikes/valuetype_capture.py`, which retakes them from the live fixture and
//! compares outside the padding — clause (b) of the licensing boundary, the
//! output of a program we ran, describing IDL we wrote. Each type is recorded
//! in a little-endian and a big-endian stream; omniORB writes the
//! encapsulation little-endian in both, so the big-endian recording is the one
//! where the stream's order and the body's differ.
//!
//! The sibling `orbweaver-giop/tests/valuetype_typecode_from_a_peer.rs` holds
//! the **codec** to these bytes. This file holds the **registry** to them: what
//! `Registry::load` derives from `corpus/golden/20-deferred-valuetype.idl` and
//! `corpus/golden/deferred-reach.idl` must equal what omniidl derived from the
//! same text, by `==` — id, name, ValueModifier, concrete base, and every
//! member's name, type and visibility, in order.
//!
//! Until 2026-08-20 it was false for every one of them, and not subtly:
//! the registry recorded a `valuetype` **and** an abstract interface as
//! `TypeCode::ObjRef`, so `gc20::Money` was an object reference here and a
//! `tk_value` with three public members there. Nothing was red, because
//! nothing compared the two — the registry's shape had never been put beside a
//! peer's for these constructs, and both emitters read the registry. The cost
//! was that `gc20::Wallet::balance()` generated as returning a reference where
//! the peer sends a value.
//!
//! *레지스트리가 valuetype과 abstract interface를 모두 `ObjRef`로 기록했고,
//! 그것을 피어의 것과 비교하는 곳이 없었다. 이 파일이 그 비교다.*


/// (what, corpus file, repository id, the peer's bytes, the stream's order).
type Recording = (&'static str, &'static str, &'static str, &'static [u8], Endian);

fn recordings() -> Vec<Recording> {
    let g20 = "20-deferred-valuetype.idl";
    let gdr = "deferred-reach.idl";
    let (le, be) = (Endian::Little, Endian::Big);
    vec![
        ("Money LE", g20, "IDL:gc20/Money:1.0", GC20_MONEY_LITTLE, le),
        ("Money BE", g20, "IDL:gc20/Money:1.0", GC20_MONEY_BIG, be),
        ("Named LE", g20, "IDL:gc20/Named:1.0", GC20_NAMED_LITTLE, le),
        ("Named BE", g20, "IDL:gc20/Named:1.0", GC20_NAMED_BIG, be),
        // The abstract interface, through the struct that holds one: an
        // interface's entry carries no `TypeCode`, so `gcdr::Tagged` is where
        // the registry's answer for an abstract interface is observable.
        ("Tagged LE", gdr, "IDL:gcdr/Tagged:1.0", GCDR_TAGGED_LITTLE, le),
        ("Tagged BE", gdr, "IDL:gcdr/Tagged:1.0", GCDR_TAGGED_BIG, be),
        ("Memo LE", gdr, "IDL:gcdr/Memo:1.0", GCDR_MEMO_LITTLE, le),
        ("Memo BE", gdr, "IDL:gcdr/Memo:1.0", GCDR_MEMO_BIG, be),
    ]
}

fn golden(name: &str) -> Registry {
    let path: PathBuf =
        Path::new(env!("CARGO_MANIFEST_DIR")).join("../..").join("corpus/golden").join(name);
    let src = std::fs::read_to_string(&path)
        .unwrap_or_else(|e| panic!("cannot read {}: {e}", path.display()));
    let spec =
        orbweaver_idl::parse(&src).unwrap_or_else(|e| panic!("{} must parse: {e}", path.display()));
    let mut reg = Registry::new();
    reg.load(&spec).unwrap_or_else(|e| panic!("{} must load: {e}", path.display()));
    reg
}

/// Every recording, both stream orders, one pass: what omniORB wrote, decoded,
/// **equals** what the registry derives from the same IDL. The whole
/// `TypeCode`, not a projection — a projection is where a wrong kind hides,
/// and a wrong kind is exactly what was here.
#[test]
fn the_registry_derives_the_value_typecode_omniidl_derives() {
    let mut failures = Vec::new();
    for (what, file, id, bytes, endian) in recordings() {
        let peer = match decode(&mut Decoder::new(bytes, endian)) {
            Ok(tc) => tc,
            Err(e) => {
                failures.push(format!("{what}: the peer's bytes do not decode: {e}"));
                continue;
            }
        };
        let ours = golden(file).typecode(id).unwrap_or_else(|| panic!("{file}: {id}")).clone();
        if ours != peer {
            failures.push(format!("{what}: not equal\n    ours {ours:?}\n    peer {peer:?}"));
        }
    }
    assert!(failures.is_empty(), "{} failure(s):\n  {}", failures.len(), failures.join("\n  "));
}

/// The composition a peer actually meets: our `TypeCode` encoded by us, in
/// either byte order, read back, equals the peer's IDL-derived one.
#[test]
fn ours_re_encoded_reads_back_equal_to_the_peers_in_either_byte_order() {
    let mut failures = Vec::new();
    for (what, file, id, bytes, endian) in recordings() {
        let peer = decode(&mut Decoder::new(bytes, endian)).expect("the peer's bytes decode");
        let ours = golden(file).typecode(id).unwrap_or_else(|| panic!("{file}: {id}")).clone();
        for out in [Endian::Big, Endian::Little] {
            let mut e = Encoder::new(out);
            encode(&mut e, &ours).expect("encode");
            let wire = e.finish().expect("finish");
            match decode(&mut Decoder::new(&wire, out)) {
                Err(e) => failures.push(format!("{what} via {out:?}: ours does not decode: {e}")),
                Ok(back) if back != peer => {
                    failures.push(format!("{what} via {out:?}: {back:?} != the peer's {peer:?}"))
                }
                Ok(_) => {}
            }
        }
    }
    assert!(failures.is_empty(), "{} failure(s):\n  {}", failures.len(), failures.join("\n  "));
}

/// The kinds, asserted on our side as well as the peer's.
///
/// The equality above would already fail if the registry went back to
/// `ObjRef`, but it would fail as a wall of `Debug` output. This says the one
/// sentence: a valuetype is not a reference and an abstract interface is not a
/// reference, and neither is the other.
#[test]
fn the_registry_never_calls_either_of_them_an_object_reference() {
    let g20 = golden("20-deferred-valuetype.idl");
    assert!(
        matches!(g20.typecode("IDL:gc20/Money:1.0"), Some(TypeCode::Value { .. })),
        "{:?}",
        g20.typecode("IDL:gc20/Money:1.0")
    );
    let gdr = golden("deferred-reach.idl");
    let subject = match gdr.typecode("IDL:gcdr/Tagged:1.0") {
        Some(TypeCode::Struct { members, .. }) => members[0].tc.clone(),
        other => panic!("gcdr::Tagged is not a struct: {other:?}"),
    };
    assert!(matches!(subject, TypeCode::AbstractInterface { .. }), "{subject:?}");
    // And a plain interface still is one, so the split is a distinction and
    // not a rename. `gcdr::Counter` holds a `Teller`, which is a plain
    // interface the §4.4 rule refuses for an unrelated reason (it raises an
    // exception carrying `fixed`) — a reference to it is still a reference,
    // and the same struct is what the Python emitter used to write an unnamed
    // TypeCode for.
    let window = match gdr.typecode("IDL:gcdr/Counter:1.0") {
        Some(TypeCode::Struct { members, .. }) => members[0].tc.clone(),
        other => panic!("gcdr::Counter is not a struct: {other:?}"),
    };
    assert!(matches!(&window, TypeCode::ObjRef { name, .. } if name == "Teller"), "{window:?}");
}
